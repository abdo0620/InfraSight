// Builds a PDF for one case with jsPDF (loaded globally as window.jspdf in index.html).
import { fmtDate } from '../../shared/format.js';

export function buildReportPdf(rep, c) {
  const lib = window.jspdf;
  if (!lib) throw new Error('PDF library not loaded. Check your internet connection.');
  const doc = new lib.jsPDF({ unit: 'mm', format: 'a4' });
  const M = 18, W = 210 - M * 2;
  let y = 22;
  const ensure = (h) => { if (y + h > 275) { doc.addPage(); y = 22; } };
  const section = (t) => { ensure(14); doc.setFont('helvetica', 'bold'); doc.setFontSize(11); doc.setTextColor(0); doc.text(t, M, y); y += 6; doc.setFont('helvetica', 'normal'); doc.setFontSize(10); };
  const kv = (k, v) => {
    const lines = doc.splitTextToSize(String(v || '-'), W - 45);
    ensure(lines.length * 5 + 2);
    doc.setTextColor(120); doc.text(k, M, y);
    doc.setTextColor(0); doc.text(lines, M + 45, y);
    y += lines.length * 5 + 1.5;
  };

  doc.setFont('helvetica', 'bold'); doc.setFontSize(20); doc.text('Infrastructure Case Report', M, y);
  y += 7;
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(120);
  doc.text(`${rep.id}  |  Generated ${fmtDate(rep.createdAt)}`, M, y);
  y += 5; doc.setDrawColor(220); doc.line(M, y, M + W, y); y += 8;

  section('Case summary');
  kv('Case ID', c.id); kv('Location', c.location); kv('Submitted', fmtDate(c.createdAt));
  kv('Status', c.status); kv('Damage type', c.type); kv('Severity', `${c.severity} / 10`); kv('Priority', c.priority);
  y += 4;

  if (c.before && c.after) {
    const w = (W - 6) / 2;
    const p = doc.getImageProperties(c.before);
    const h = (w * p.height) / p.width;
    ensure(h + 20);
    section('Before and after');
    doc.setFontSize(9); doc.setTextColor(120);
    doc.text('Before', M, y); doc.text('After (AI preview)', M + w + 6, y);
    y += 2;
    doc.addImage(c.before, 'JPEG', M, y, w, h);
    doc.addImage(c.after, 'JPEG', M + w + 6, y, w, h);
    y += h + 8; doc.setFontSize(10);
  }

  const r = c.report || {};
  section('Engineering assessment');
  kv('Tripping hazard', r.tripping_hazard);
  kv('Exposed materials', (r.exposed_materials || []).join(', '));
  kv('Accessibility', r.accessibility_impact);
  kv('Recommended action', r.recommended_action);

  if (c.note) {
    y += 4; section("Citizen's note");
    const lines = doc.splitTextToSize(c.note, W);
    ensure(lines.length * 5);
    doc.setTextColor(0); doc.text(lines, M, y);
  }

  const n = doc.getNumberOfPages();
  for (let i = 1; i <= n; i++) {
    doc.setPage(i); doc.setFontSize(8); doc.setTextColor(150);
    doc.text('Generated by InfraSight. AI-assisted assessment; verify on site before action.', M, 287);
    doc.text(`${i} / ${n}`, 210 - M, 287, { align: 'right' });
  }
  return doc;
}
